#[cfg(not(feature = "lfn"))]
fn glyph_bits(ch: u8) -> [u8; 5] {
    match ch {
        b'-'..=b'Z' => FONT[(ch - b'-') as usize],
        b'_' => FONT[46],
        b'~' => FONT[47],
        _ => [0; 5],
    }
}

pub fn glyph(x: u16, y: u16, ch: u8, bg: u16) {
    let g = glyph_bits(ch);
    win(x, y, x + 11, y + 15);
    let mut ry = 0;
    while ry < 16 {
        let mut cx = 0;
        while cx < 12 {
            let on = cx < 10 && ry < 14 && g[cx / 2] >> (ry / 2) & 1 != 0;
            d(if on { 0xFFFF } else { bg });
            cx += 1;
        }
        ry += 1;
    }
}

#[inline(never)]
pub fn fill(x: u16, y: u16, w: u16, h: u16, color: u16) {
    win(x, y, x + w - 1, y + h - 1);
    let mut n = w as u32 * h as u32;
    while n > 0 {
        d(color);
        n -= 1;
    }
}

#[inline(never)]
pub fn text(x: u16, y: u16, s: &[u8], bg: u16) {
    let mut px = x;
    for &c in s {
        glyph(px, y, c, bg);
        px += 12;
    }
}

/// A 24 px row from `x` to the right edge.
#[inline(never)]
pub fn row(x: u16, y: u16, s: &[u8], bg: u16) {
    fill(x, y, 480 - x, 24, bg);
    text(x, y + 4, s, bg);
}
