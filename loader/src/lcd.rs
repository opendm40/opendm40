//! ILI9488 on FSMC NE1 (firmware/src/board.rs), 12x16 text cells: 40 x 20.
use crate::hw::*;

const CMD: u32 = 0x6001_FFFE;
const DATA: u32 = 0x6002_0000;

#[inline(never)]
fn c(v: u16) {
    w16(CMD, v)
}
#[inline(always)]
fn d(v: u16) {
    w16(DATA, v)
}

const SEQ: &[u8] = &[
    0xC0, 2, 0x0F, 0x0F, //
    0xC1, 1, 0x41, //
    0xC5, 3, 0x00, 0x57, 0x80, //
    0xB1, 1, 0xA0, //
    0xB4, 1, 0x02, //
    0x3A, 1, 0x55, //
    0x21, 0, //
    0xE9, 1, 0x00, //
    0xF7, 4, 0xA9, 0x51, 0x2C, 0x82, //
    0xE0, 15, 0x00, 0x09, 0x0C, 0x02, 0x0E, 0x05, 0x2F, 0x46, 0x47, 0x04, 0x0E, 0x0B, 0x2D, 0x36, 0x0F, //
    0xE1, 15, 0x00, 0x10, 0x13, 0x03, 0x10, 0x06, 0x3A, 0x46, 0x51, 0x06, 0x10, 0x0D, 0x33, 0x37, 0x0F, //
    0x36, 1, 0xE8, // landscape
];

#[inline(never)]
fn seq(s: &[u8]) {
    let mut t = s;
    while let [cmd, n, rest @ ..] = t {
        c(*cmd as u16);
        let (a, b) = rest.split_at(*n as usize);
        for v in a {
            d(*v as u16);
        }
        t = b;
    }
}

#[inline(never)]
pub fn init() {
    set(RCU_AHB3EN, 1);
    w(0xA000_0004, 0x0000_0F04); // BTR1
    w(0xA000_0104, 0x0FF0_0201); // BWTR1
    w(0xA000_0000, 0x0000_5091); // BCR1
    ms(20);
    seq(SEQ);
    c(0x11);
    ms(120);
    c(0x29);
    fill(0, 0, 480, 320, 0);
    // Backlight on, constant.
    w(GPIOA + BOP, 1 << 6);
}

fn pair(cmd: u16, a: u16, b: u16) {
    c(cmd);
    d(a >> 8);
    d(a & 0xFF);
    d(b >> 8);
    d(b & 0xFF);
}

fn win(x: u16, y: u16, xe: u16, ye: u16) {
    pair(0x2A, x, xe);
    pair(0x2B, y, ye);
    c(0x2C);
}

