#!/usr/bin/env python3
"""Rasterise the round Wiren Board logo for the status bars of opendm40.

Source: fonts/wb-logo-round.png (212x212 RGBA, the official wirenboard/brand
logos/logo-round: green #5cb400 circle, white "wb" mark; the SVG next to it
is the same drawing). Output: src/stockfont_logo.rs with two 4 bpp coverage
planes of an N x N box-filtered (area-average) downscale, row-major, two
pixels per byte, high nibble first:
  LOGO_C  circle coverage (green over the bar background),
  LOGO_M  white mark coverage (white over the result),
so stockfont::logo() blends against whatever background the bar has.

Also src/splash_logo.rs for the boot splash (src/splash.rs): the wide
"wirenboard" board logo, fonts/wb-logo-horizontal.svg (wirenboard/brand
logos/logo-horizontal), SPLASH_W px wide, rasterised by Inkscape at 10x
and box-filtered:
  BOARD_HALF  the green board's half height at each column boundary of the
              left half (x = 0 .. SPLASH_W / 2), 1/8 px; the board is
              symmetric about both axes, splash.rs mirrors it and
              anti-aliases with 4 sub-columns per pixel;
  TEXT_*      the white lettering's coverage in 3 levels (0, 1/2, 1),
              cropped to its box, row-major, as runs: one nibble each,
              bit 3 = the next value ((v + 1) % 3 or (v + 2) % 3, from a
              virtual v = 2), bits 0-2 = run length 1..6; 7 = 7 + the
              next nibble (7..22); 0 = the next three nibbles are the
              length (12 bits). High nibble first.
3 levels in this run code are about 510 bytes at 200 px; 1 bpp runs are
smaller (~360) but jagged on the round letters, 2x-supersampled 1 bpp
runs ~900.

    /usr/bin/python3 tools/mklogo.py [N]      (default N = 20; needs inkscape)
"""
import os
import sys

from PIL import Image

N = int(sys.argv[1]) if len(sys.argv) > 1 else 20
here = os.path.dirname(os.path.abspath(__file__))
src = Image.open(os.path.join(here, '..', 'fonts', 'wb-logo-round.png')).convert('RGBA')
w, h = src.size
circ = Image.new('L', src.size)
mark = Image.new('L', src.size)
cp, mp = circ.load(), mark.load()
sp = src.load()
for y in range(h):
    for x in range(w):
        r, g, b, a = sp[x, y]
        cp[x, y] = a
        # Pixel = lerp(green, white, m) inside the circle: m from the red channel.
        m = max(0.0, min(1.0, (r - 92) / (255 - 92)))
        mp[x, y] = round(m * a)


def plane(im):
    small = im.resize((N, N), Image.BOX)
    v = [round(p * 15 / 255) for p in small.tobytes()]
    if len(v) % 2:
        v.append(0)
    return bytes(v[i] << 4 | v[i + 1] for i in range(0, len(v), 2))


def rs(name, data):
    rows = ['    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    return 'pub static %s: [u8; %d] = [\n%s\n];\n' % (name, len(data), '\n'.join(rows))


out = ['// Generated by tools/mklogo.py from fonts/wb-logo-round.png -- do not edit.',
       '// Round Wiren Board logo, %dx%d, 4 bpp coverage planes (see the script).' % (N, N),
       'pub const LOGO_N: usize = %d;' % N,
       rs('LOGO_C', plane(circ)), rs('LOGO_M', plane(mark))]
open(os.path.join(here, '..', 'src', 'stockfont_logo.rs'), 'w').write('\n'.join(out))
print('src/stockfont_logo.rs: %dx%d, %d bytes of data' % (N, N, 2 * len(plane(circ))))



# --- the boot splash's wide logo --------------------------------------------

SPLASH_W = 200
import subprocess
import tempfile

svg = open(os.path.join(here, '..', 'fonts', 'wb-logo-horizontal.svg')).read()
tmp = tempfile.mkdtemp()


def layer(name, text):
    """One layer (board / lettering) as coverage 0..255 at 10x."""
    sp = os.path.join(tmp, name + '.svg')
    pp = os.path.join(tmp, name + '.png')
    open(sp, 'w').write(text)
    subprocess.run(['inkscape', sp, '--export-type=png', '--export-filename=' + pp, '--export-width=3972',
                    '--export-background=white', '--export-background-opacity=1'],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return Image.eval(Image.open(pp).convert('L'), lambda p: 255 - p)


board = layer('board', svg.replace('fill: #fff;', 'fill: none;').replace('#5cb400', '#000'))
text = layer('text', svg.replace('#5cb400', 'none').replace('fill: #fff', 'fill: #000'))
bb = board.getbbox()
sc = SPLASH_W / (bb[2] - bb[0])
SPLASH_H = round((bb[3] - bb[1]) * sc / 2) * 2
cy = (bb[1] + bb[3]) / 2  # centre row, 10x units
# Board half height at each column boundary of the left half (mirrored).
bp = board.load()
half = []
for i in range(SPLASH_W // 2 + 1):
    x = min(bb[2] - 1, max(bb[0], int(bb[0] + i / sc)))
    y = bb[1]
    while y < cy and bp[x, y] < 128:
        y += 1
    half.append(min(255, round((cy - y) * sc * 8)))
# Lettering: the same frame as the board, box-filtered, 3 levels.
tframe = text.crop((bb[0], round(cy - SPLASH_H / 2 / sc), bb[2], round(cy + SPLASH_H / 2 / sc)))
tsm = tframe.resize((SPLASH_W, SPLASH_H), Image.BOX)
tx0, ty0, tx1, ty1 = tsm.getbbox()
lv = [0 if p < 85 else 1 if p < 170 else 2 for p in tsm.crop((tx0, ty0, tx1, ty1)).tobytes()]
nibs = []
v = 2
i = 0
while i < len(lv):
    j = i
    while j < len(lv) and lv[j] == lv[i]:
        j += 1
    n = j - i
    d = 0 if lv[i] == (v + 1) % 3 else 1
    if n <= 6:
        nibs.append(d << 3 | n)
    elif n <= 22:
        nibs += [d << 3 | 7, n - 7]
    else:
        nibs += [d << 3, n >> 8 & 15, n >> 4 & 15, n & 15]
    v = lv[i]
    i = j
if len(nibs) % 2:
    nibs.append(0)
tdata = bytes(nibs[k] << 4 | nibs[k + 1] for k in range(0, len(nibs), 2))
out = ['// Generated by tools/mklogo.py from fonts/wb-logo-horizontal.svg -- do not edit.',
       '// Boot splash: the wide Wiren Board logo, %dx%d (see the script).' % (SPLASH_W, SPLASH_H),
       'pub const SPLASH_W: i16 = %d;' % SPLASH_W,
       'pub const SPLASH_H: i16 = %d;' % SPLASH_H,
       rs('BOARD_HALF', bytes(half)),
       '/// The lettering\'s box inside the logo: x, y, w, h.',
       'pub const TEXT_BOX: (i16, i16, i16, i16) = (%d, %d, %d, %d);' % (tx0, ty0, tx1 - tx0, ty1 - ty0),
       '/// Region A2 (link-native.x: the one boot-only exception there, the first',
       '/// to move out if A2 is needed for hot data; region C is contended).',
       '#[cfg_attr(target_os = "none", link_section = ".rodata.a2.splash_text")]',
       rs('TEXT_RUNS', tdata)]
open(os.path.join(here, '..', 'src', 'splash_logo.rs'), 'w').write('\n'.join(out))
print('src/splash_logo.rs: %dx%d, board %d + lettering %d bytes' % (SPLASH_W, SPLASH_H, len(half), len(tdata)))
