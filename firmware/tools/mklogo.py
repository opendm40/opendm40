#!/usr/bin/env python3
"""Rasterise the round Wiren Board logo for the status bars of opendm40.

Source: fonts/wb-logo-round.png (212x212 RGBA, the official wirenboard/brand
logos/logo-round: green #5cb400 circle, white "wb" mark; the SVG next to it
is the same drawing). Output: src/stockfont_logo.rs with two 4 bpp coverage
planes of an N x N box-filtered (area-average) downscale, row-major, two
pixels per byte, high nibble first:
  LOGO_C  circle coverage (green over the bar background),
  LOGO_M  white mark coverage (white over the result),
so stockfont::logo() blends against whatever background the bar has.

Also src/splash_logo.rs for the boot splash (native/splash.rs): only the
white mark of a SPLASH_N x SPLASH_N downscale, 1 bpp (coverage > 50 %),
cropped to its bounding box, row-major, bits continuous, MSB first; the
green circle is drawn by code. Plain bits are smaller than a byte-run RLE
of the same mark (142 vs 167 bytes at 64 px).

    /usr/bin/python3 tools/mklogo.py [N]      (default N = 20)
"""
import os
import sys

from PIL import Image

N = int(sys.argv[1]) if len(sys.argv) > 1 else 20
here = os.path.dirname(os.path.abspath(__file__))
src = Image.open(os.path.join(here, '..', 'fonts', 'wb-logo-round.png')).convert('RGBA')
w, h = src.size
circ = Image.new('L', src.size)
mark = Image.new('L', src.size)
cp, mp = circ.load(), mark.load()
sp = src.load()
for y in range(h):
    for x in range(w):
        r, g, b, a = sp[x, y]
        cp[x, y] = a
        # Pixel = lerp(green, white, m) inside the circle: m from the red channel.
        m = max(0.0, min(1.0, (r - 92) / (255 - 92)))
        mp[x, y] = round(m * a)


def plane(im):
    small = im.resize((N, N), Image.BOX)
    v = [round(p * 15 / 255) for p in small.tobytes()]
    if len(v) % 2:
        v.append(0)
    return bytes(v[i] << 4 | v[i + 1] for i in range(0, len(v), 2))


def rs(name, data):
    rows = ['    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    return 'pub static %s: [u8; %d] = [\n%s\n];\n' % (name, len(data), '\n'.join(rows))


out = ['// Generated by tools/mklogo.py from fonts/wb-logo-round.png -- do not edit.',
       '// Round Wiren Board logo, %dx%d, 4 bpp coverage planes (see the script).' % (N, N),
       'pub const LOGO_N: usize = %d;' % N,
       rs('LOGO_C', plane(circ)), rs('LOGO_M', plane(mark))]
open(os.path.join(here, '..', 'src', 'stockfont_logo.rs'), 'w').write('\n'.join(out))
print('src/stockfont_logo.rs: %dx%d, %d bytes of data' % (N, N, 2 * len(plane(circ))))


SPLASH_N = 64
m = mark.resize((SPLASH_N, SPLASH_N), Image.BOX)
x0, y0, x1, y1 = m.getbbox()
bits = [1 if p > 127 else 0 for p in m.crop((x0, y0, x1, y1)).tobytes()]
bits += [0] * (-len(bits) % 8)
data = bytes(sum(b << (7 - k) for k, b in enumerate(bits[i:i + 8])) for i in range(0, len(bits), 8))
out = ['// Generated by tools/mklogo.py from fonts/wb-logo-round.png -- do not edit.',
       '// Boot splash: the white mark of the round Wiren Board logo at %dx%d, 1 bpp (see the script).' % (SPLASH_N, SPLASH_N),
       'pub const SPLASH_N: i16 = %d;' % SPLASH_N,
       '/// Bounding box of the mark inside the SPLASH_N square: x, y, w, h.',
       'pub const MARK: (i16, i16, i16, i16) = (%d, %d, %d, %d);' % (x0, y0, x1 - x0, y1 - y0),
       rs('MARK_BITS', data)]
open(os.path.join(here, '..', 'src', 'splash_logo.rs'), 'w').write('\n'.join(out))
print('src/splash_logo.rs: %dx%d mark, %d bytes of data' % (x1 - x0, y1 - y0, len(data)))
