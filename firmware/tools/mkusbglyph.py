#!/usr/bin/env python3
"""Generate src/stockfont_usb.rs: the USB symbol (the trident, upright) as
glyph 0x22 of the stock status-bar icon font SAVE_BT (0x0805B2E8, 0x21 =
Bluetooth, 16 x 20 4 bpp), for the status bar's "USB host" icon (ui.rs
status_right). The stock firmware has no USB icon.

Drawn at 8x with PIL (stem with an arrow head, a round foot, a branch with a
circle on the left and one with a square on the right, ~2 px strokes like the
Bluetooth glyph), area-averaged to 14 x 20, quantised to 4 bpp alpha,
column-major, high nibble first (stockfont.rs RAW4).

    /usr/bin/python3 tools/mkusbglyph.py      (from firmware/; needs PIL)
"""
import os
import sys

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'stockfont_usb.rs')
W, H, K = 14, 20, 8


def draw():
    im = Image.new('L', (W * K, H * K), 0)
    d = ImageDraw.Draw(im)
    s = 2 * K  # stroke
    cx = W * K // 2
    # Arrow head on top, stem down to the foot.
    d.polygon([(cx, 0), (cx - 3 * K, 4 * K), (cx + 3 * K, 4 * K)], fill=255)
    d.rectangle((cx - s / 2, 3.5 * K, cx + s / 2, 17 * K), fill=255)
    # Round foot.
    r = 2.1 * K
    d.ellipse((cx - r, 20 * K - 2 * r, cx + r, 20 * K), fill=255)
    # Left branch: from the stem down-left, then up, a circle on top.
    lx = 1.8 * K
    d.line([(cx, 15 * K), (lx, 12 * K)], fill=255, width=s)
    d.rectangle((lx - s / 2, 9.5 * K, lx + s / 2, 12.4 * K), fill=255)
    rc = 1.8 * K
    d.ellipse((lx - rc, 10 * K - 2 * rc, lx + rc, 10 * K), fill=255)
    # Right branch: higher, a square on top.
    rx = W * K - 1.8 * K
    d.line([(cx, 12 * K), (rx, 9 * K)], fill=255, width=s)
    d.rectangle((rx - s / 2, 7.5 * K, rx + s / 2, 9.4 * K), fill=255)
    q = 1.6 * K
    d.rectangle((rx - q, 7.6 * K - 2 * q, rx + q, 7.6 * K), fill=255)
    r = im.resize((W, H), Image.BOX)
    return [[min(15, (r.getpixel((x, y)) + 8) // 17) for x in range(W)] for y in range(H)]


def main():
    px = draw()
    nib = [px[y][x] for x in range(W) for y in range(H)]
    if len(nib) % 2:
        nib.append(0)
    b = bytes(nib[i] << 4 | nib[i + 1] for i in range(0, len(nib), 2))
    lines = ['// @generated by tools/mkusbglyph.py - do not edit by hand.',
             '// The USB symbol as SAVE_BT glyph 0x22 (stockfont.rs glyph_or_twin):',
             '// (font object address, char, 4 bpp, w, h, adv, yoff, column-major bitmap).']
    for row in px:
        lines.append('//   ' + ''.join('.:-=+*#%@@'[min(9, v * 10 // 16)] for v in row))
    lines.append('pub static USB_GLYPH: (u32, char, bool, u8, u8, u8, i8, &[u8]) =')
    lines.append('    (0x0805B2E8, \'\\u{22}\', true, %d, %d, %d, 0, b"%s");' % (W, H, W, ''.join('\\x%02x' % c for c in b)))
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('src/stockfont_usb.rs written')


if __name__ == '__main__':
    sys.exit(main())
