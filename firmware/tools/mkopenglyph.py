#!/usr/bin/env python3
"""Generate src/stockfont_open.rs: the letters of "OPEN" that the stock
fonts lack (stockfont.rs glyph_or_twin), for continuity / diode with open
leads (owner 2026-10-30: "OPEN" instead of "0L").

  F78 (main readout, has O and L): P and N from FreeSans Bold scaled by the
      stock L ink box / FreeSans L ink box (x and y: same cap height, the
      stems come out at the L's 15 px), yoff and advance-minus-width of the
      L; E built from the stock L itself (its stem and bottom bar, the bar
      repeated at the top and the middle, shorter).
  K_FONT (SC_DIGITS: the scope page's meter strip, has O and N): E from the
      stock F (its top bar repeated at the bottom), P from FreeSans Bold
      scaled by the stock R.

The bitmaps are RLE4 (mkstockfont.py rle_glyph) in one blob in region A2
(`.rodata.a2.*`, zero-wait flash).

    /usr/bin/python3 tools/mkopenglyph.py      (from firmware/; needs PIL + the face)
"""
import ast
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
sys.path.insert(0, HERE)
import mkstockfont  # noqa: E402

FACE = '/usr/share/fonts/truetype/freefont/FreeSansBold.ttf'
SS = 400
F78, K_FONT = 0x08065070, 0x0805C5DC


def load(s, name):
    m = re.search(r'pub static %s_E: \[Entry; \d+\] = \[(.*?)\];' % name, s, re.S)
    ents = {}
    for e in re.findall(r'E\(([^)]*)\)', m.group(1)):
        v = [int(x, 0) for x in e.split(',')]
        ents[v[0]] = v
    m = re.search(r'pub static %s_B: \[u8; (\d+)\] = \*b"' % name, s)
    i = st = m.end()
    while s[i] != '"':
        i += 2 if s[i] == '\\' else 1
    return ents, ast.literal_eval('b"' + s[st:i].replace('\\\n', '') + '"')


def glyph(f, ch):
    ents, blob = f
    _, off, w, h, adv, yoff, _, _ = ents[ord(ch)]
    px = mkstockfont.unrle_glyph(blob[off:], w, h)
    return dict(w=w, h=h, adv=adv, yoff=yoff, rows=[[px[x * h + y] for x in range(w)] for y in range(h)])


def nat(ch):
    f = ImageFont.truetype(FACE, SS)
    im = Image.new('L', (SS * 2, SS * 2), 0)
    ImageDraw.Draw(im).text((SS // 2, SS // 2), ch, font=f, fill=255)
    return im.crop(im.getbbox())


def from_face(ch, ref, rg):
    r0, g = nat(ref), nat(ch)
    sx, sy = rg['w'] / r0.size[0], rg['h'] / r0.size[1]
    w, h = max(1, round(g.size[0] * sx)), round(g.size[1] * sy)
    r = g.resize((w, h), Image.BOX)
    rows = [[min(15, (r.getpixel((x, y)) + 8) // 17) for x in range(w)] for y in range(h)]
    return dict(w=w, h=h, adv=w + rg['adv'] - rg['w'], yoff=rg['yoff'], rows=rows)


def e_from_l(lg):
    """F78 E: the L's stem and bottom bar; the bar again at the top (2 px
    shorter) and in the middle (6 px shorter)."""
    w, h = lg['w'] - 2, lg['h']
    bar = [y for y in range(h) if lg['rows'][y][w - 4] >= 8]
    t = len(bar)
    stem = lg['rows'][h // 2]
    rows = [[stem[x] if x < w else 0 for x in range(w)] for _ in range(h)]
    mid = (h - t) // 2
    for k in range(t):
        rows[h - t + k] = [15] * w
        rows[k] = [15] * (w - 2) + [0, 0]
        rows[mid + k] = [15] * (w - 6) + [0] * 6
    return dict(w=w, h=h, adv=w + lg['adv'] - lg['w'], yoff=lg['yoff'], rows=rows)


def e_from_f(fg):
    """K_FONT E: the F with its top bar mirrored at the bottom."""
    rows = [r[:] for r in fg['rows']]
    ink = [y for y in range(fg['h']) if fg['rows'][y][fg['w'] - 1]]
    for y in ink:
        rows[fg['h'] - 1 - y] = fg['rows'][y][:]
    return dict(fg, rows=rows)


def main():
    s = open(os.path.join(SRC, 'stockfont_data.rs')).read()
    f78, kf = load(s, 'F78'), load(s, 'K_FONT')
    lg = glyph(f78, 'L')
    gl = [(F78, 'P', from_face('P', 'L', lg)), (F78, 'E', e_from_l(lg)), (F78, 'N', from_face('N', 'L', lg)),
          (K_FONT, 'P', from_face('P', 'R', glyph(kf, 'R'))), (K_FONT, 'E', e_from_f(glyph(kf, 'F')))]
    blob = b''
    ents = []
    art = []
    for addr, ch, g in gl:
        assert g['w'] <= mkstockfont.MAXW
        px = [g['rows'][y][x] for x in range(g['w']) for y in range(g['h'])]
        b = mkstockfont.rle_glyph(px, g['w'], g['h'])
        assert mkstockfont.unrle_glyph(b, g['w'], g['h']) == px
        ents.append('    (0x%08X, \'%s\', %d, %d, %d, %d, %d),' % (addr, ch, len(blob), g['w'], g['h'], g['adv'], g['yoff']))
        art.append('// %s %s (%d x %d, %d B)' % ('F78' if addr == F78 else 'K_FONT', ch, g['w'], g['h'], len(b)))
        for y in range(0, g['h'], 2 if g['h'] > 40 else 1):
            art.append('//   ' + ''.join('.:-=+*#%@@'[min(9, v * 10 // 16)] for v in g['rows'][y]))
        blob += b
    lines = ['// @generated by tools/mkopenglyph.py - do not edit by hand.',
             '// The letters of "OPEN" the stock F78 / K_FONT lack (stockfont.rs glyph_or_twin):',
             '// (font object address, char, offset into OPEN_B, w, h, adv, yoff), RLE4.', '']
    lines += art
    lines += ['', '#[link_section = ".rodata.a2.OPEN_T"]', 'static OPEN_GLYPHS: [(u32, char, u16, u8, u8, u8, i8); %d] = [' % len(ents)] + ents + ['];',
              '#[link_section = ".rodata.a2.OPEN"]',
              'static OPEN_B: [u8; %d] = *b"%s";' % (len(blob), ''.join('\\x%02x' % c for c in blob))]
    open(os.path.join(SRC, 'stockfont_open.rs'), 'w').write('\n'.join(lines) + '\n')
    print('src/stockfont_open.rs written: %d B of RLE4' % len(blob))


if __name__ == '__main__':
    sys.exit(main())
