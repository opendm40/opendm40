#!/usr/bin/env python3
"""Generate the localized images' tables (src/lang.rs) from i18n/<lang>.tsv:
src/tr_<lang>.rs, the `tr!` macro (one arm per translated string: the build
puts only the translation in the image), and src/lang_<lang>.rs, the glyphs.

    /usr/bin/python3 -I tools/mklang.py <lang> [--check]

Chinese: FreeType's mono rendering of Noto Sans CJK SC Regular at 14 px, only
the characters used; each hanzi is U+0400 + its glyph index (two UTF-8 bytes).
Licence: i18n/OFL-NotoSansCJK.txt; the font file is not in the repo (Debian:
fonts-noto-cjk). --check compares tr_<lang>.rs with the tsv, no font needed.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
NOTO_CJK = '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
ZH_SIZE = 14
BASE = 0x400

# The line height floor: text in a smaller font stays English (lang-render
# fails a translation drawn in one).
MIN_LINE = {'zh': 15, 'ru': 12, 'it': 12, 'fr': 12}


def unesc(s):
    return re.sub(r'\\u\{([0-9a-fA-F]+)\}', lambda m: chr(int(m.group(1), 16)), s)


def read_tsv(lang):
    """{English: translation} of the translated rows; the keys as the sources
    spell them (escapes kept)."""
    rows = {}
    for n, l in enumerate(open(os.path.join(FW, 'i18n', lang + '.tsv'), encoding='utf-8'), 1):
        l = l.rstrip('\n')
        if not l or l.startswith('#'):
            continue
        k, z, src = l.split('\t')
        assert (src == 'E') == (k == z) or src == 'M', 'line %d: E = the English on purpose' % n
        assert src in ('S', 'R', 'M', 'E', 'O'), 'line %d: source' % n
        assert k not in rows, 'line %d: %r twice' % (n, k)
        if unesc(k) != unesc(z):  # the same in both: no macro arm
            rows[k] = unesc(z)
    return rows


def rs_bytes(b):
    return '\n'.join('    ' + ''.join('\\x%02x' % x for x in b[i:i + 32]) + '\\' for i in range(0, len(b), 32))


def rs_str(s):
    return ''.join(c if 32 <= ord(c) < 127 and c not in '"\\' else '\\u{%x}' % ord(c) for c in s)


def tr_file(lang, enc_rows):
    """src/tr_<lang>.rs: `tr!` (and the host check's pairs, cfg lang_log)."""
    arms = ''.join('    ("%s") => { "%s" };\n' % (k, rs_str(z)) for k, z in sorted(enc_rows.items()))
    pairs = ''.join('    ("%s", "%s"),\n' % (k, rs_str(z)) for k, z in sorted(enc_rows.items()))
    return ('// Generated by tools/mklang.py from i18n/%s.tsv. Do not edit.\n'
            '/// The UI text `$s` in this image\'s language: the translation of a\n'
            '/// literal with one, else the literal (src/lang.rs).\n'
            '#[macro_export]\nmacro_rules! tr {\n%s    ($s:literal) => { $s };\n}\n\n'
            '/// ui-render (UIR_LANG): (English, translation), the check of stockfont.rs `ui_text`.\n'
            '#[cfg(lang_log)]\npub const PAIRS: &[(&str, &str)] = &[\n%s];\n'
            '#[cfg(lang_log)]\npub const MIN_LINE: u16 = %d;\n') % (lang, arms, pairs, MIN_LINE[lang])


def is_han(c):
    return ord(c) >= 0x2E80


def zh_bits(chars):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(NOTO_CJK, ZH_SIZE, index=2)
    assert 'SC' in font.getname()[0], font.getname()
    out = bytearray()
    for c in chars:
        im = Image.new('1', (ZH_SIZE, ZH_SIZE), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((ZH_SIZE // 2, ZH_SIZE // 2), c, font=font, fill=1, anchor='mm')
        bits = [1 if im.getpixel((x, y)) else 0 for x in range(ZH_SIZE) for y in range(ZH_SIZE)]
        bits += [0] * (-len(bits) % 8)
        assert any(bits), c
        for i in range(0, len(bits), 8):
            v = 0
            for b in bits[i:i + 8]:
                v = v << 1 | b
            out.append(v)
    return bytes(out)


def build_zh(rows, check):
    chars = sorted({c for z in rows.values() for c in z if is_han(c)})
    idx = {c: i for i, c in enumerate(chars)}
    enc = lambda s: ''.join(chr(BASE + idx[c]) if is_han(c) else c for c in s)
    enc_rows = {k: enc(z) for k, z in rows.items()}
    if check:
        return enc_rows, None, None
    bits = zh_bits(chars)
    gb = len(bits) // len(chars)
    s = '// Characters: %s\n' % ''.join(chars)
    s += 'pub const N: usize = %d;\npub const SIZE: u8 = %d;\npub const GB: usize = %d;\n' % (len(chars), ZH_SIZE, gb)
    s += '#[link_section = ".rodata.fonts.LANG_G"]\npub static G: [u8; %d] = *b"\\\n%s\n";\n' % (len(bits), rs_bytes(bits))
    s += 'pub static EXTRA: [(u32, FontData); 0] = [];\n'
    ntxt = sum(len(z.encode()) for z in enc_rows.values())
    return enc_rows, s, 'strings %d, glyphs %d (%d B), text %d B' % (len(enc_rows), len(chars), len(bits), ntxt)


def main():
    lang = sys.argv[1]
    check = '--check' in sys.argv
    rows = read_tsv(lang)
    if lang == 'zh':
        enc_rows, gl, stats = build_zh(rows, check)
    else:
        sys.path.insert(0, HERE)
        import mklang_x
        enc_rows, gl, stats = mklang_x.build(lang, rows, check, rs_bytes)
    tr = tr_file(lang, enc_rows)
    out = os.path.join(FW, 'src', 'tr_%s.rs' % lang)
    if check:
        if not os.path.exists(out) or open(out, encoding='utf-8').read() != tr:
            sys.exit('%s is out of date: run tools/mklang.py %s' % (out, lang))
        print('%s matches its tsv' % os.path.basename(out))
        return
    open(out, 'w', encoding='utf-8').write(tr)
    notice = '// Generated by tools/mklang.py from i18n/%s.tsv. Do not edit.\n' % lang
    open(os.path.join(FW, 'src', 'lang_%s.rs' % lang), 'w', encoding='utf-8').write(notice + gl)
    print(lang, stats)


main()
