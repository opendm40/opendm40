#!/usr/bin/env python3
"""Generate src/fonts.rs: anti-aliased 4 bpp glyphs, run-length encoded.

    /usr/bin/python3 tools/mkfont.py      (from fw-rs/)

Each glyph is stored as runs, one byte per run: high nibble = run length - 1
(1..16 pixels), low nibble = alpha (0..15), row-major over the glyph box. The
box is placed at `x_off` inside an `advance`-wide cell, `top` rows above the
baseline. Fonts are fitted to read-backs of the stock screen (fw-rs/ref/).
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ROBOTO = os.path.join(ROOT, 'fonts', 'Roboto-VF.ttf')

ASCII = ''.join(chr(c) for c in range(32, 127))

# name, ttf, weight, width, pixel size, characters
FONTS = [
    # Main reading: Roboto Bold ~105 px matches the stock digits (cap 77 px).
    ('VALUE', ROBOTO, 700, 100, 105, '0123456789.-+ OL'),
    # Unit next to the reading ('m' fits Bold 40 px within 1 %).
    ('UNIT', ROBOTO, 700, 100, 40, ' munkMGVAFHz%' + 'Ωµ°C'),
    # Status bar and labels: Roboto Regular 27 px ("AUTO", "RUN").
    ('LABEL', ROBOTO, 400, 100, 27, ASCII + 'Ωµ°'),
]


def font(path, weight, width, size):
    f = ImageFont.truetype(path, size)
    try:
        f.set_variation_by_axes([weight, width])
    except OSError:
        pass
    return f


def glyph(f, ch):
    """-> (alpha 0..15 rows, x_off, top, advance)."""
    ascent, descent = f.getmetrics()
    adv = int(round(f.getlength(ch)))
    pad = f.size
    im = Image.new('L', (adv + 2 * pad, ascent + descent + 2 * pad))
    ImageDraw.Draw(im).text((pad, pad), ch, font=f, fill=255)
    box = im.getbbox()
    if box is None:
        return [], 0, 0, adv
    x0, y0, x1, y1 = box
    rows = [[(im.getpixel((x, y)) * 15 + 127) // 255 for x in range(x0, x1)] for y in range(y0, y1)]
    x_off = x0 - pad
    if x_off < 0:            # keep the box inside the cell: shift right, widen
        adv -= x_off
        x_off = 0
    adv = max(adv, x_off + (x1 - x0))
    top = (pad + ascent) - y0  # rows above the baseline
    return rows, x_off, top, adv


def rust_char(ch):
    return {"'": "'\\''", '\\': "'\\\\'"}.get(ch, "'%s'" % ch)


def rle(rows):
    out = []
    flat = [a for r in rows for a in r]
    i = 0
    while i < len(flat):
        a = flat[i]
        n = 1
        while i + n < len(flat) and flat[i + n] == a and n < 16:
            n += 1
        out.append(((n - 1) << 4) | a)
        i += n
    return out


def main():
    lines = ['//! Generated by tools/mkfont.py -- do not edit.', '//! Roboto: SIL Open Font License, see fonts/Roboto-OFL.txt.', '',
             'use crate::text::{Font, Glyph};', '']
    total = 0
    for name, path, weight, width, size, chars in FONTS:
        f = font(path, weight, width, size)
        ascent, descent = f.getmetrics()
        data = []
        glyphs = []
        for ch in chars:
            rows, x_off, top, adv = glyph(f, ch)
            enc = rle(rows)
            w = len(rows[0]) if rows else 0
            glyphs.append((ch, len(data), w, len(rows), x_off, top, adv))
            data += enc
        total += len(data) + 12 * len(glyphs)
        lines.append('static %s_DATA: [u8; %d] = [' % (name, len(data)))
        for i in range(0, len(data), 24):
            lines.append('    ' + ' '.join('0x%02x,' % b for b in data[i:i + 24]))
        lines.append('];')
        lines.append('static %s_GLYPHS: [Glyph; %d] = [' % (name, len(glyphs)))
        for ch, off, w, h, x_off, top, adv in glyphs:
            lines.append('    Glyph { ch: %s, off: %d, w: %d, h: %d, x_off: %d, top: %d, adv: %d },'
                         % (rust_char(ch), off, w, h, x_off, top, adv))
        lines.append('];')
        lines.append('pub static %s: Font = Font { ascent: %d, descent: %d, glyphs: &%s_GLYPHS, data: &%s_DATA };'
                     % (name, ascent, descent, name, name))
        lines.append('')
        print('%-6s %3d px wght %d: %3d glyphs, %6d bytes' % (name, size, weight, len(glyphs), len(data)))
    out = os.path.join(ROOT, 'src', 'fonts.rs')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('total ~%d bytes -> %s' % (total, out))


if __name__ == '__main__':
    main()
