#!/usr/bin/env python3
"""Generate src/hy3131_tables.rs from firmware/re/analysis/hy3131_v2_6.h
(the R20..R35 configuration rows per mode/range).

    /usr/bin/python3 tools/mktables.py      (from fw-rs/)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(ROOT, '..', 'firmware', 're', 'analysis', 'hy3131_v2_6.h')

src = open(HDR).read()
out = ['//! Generated by tools/mktables.py from firmware/re/analysis/hy3131_v2_6.h -- do not edit.',
       '//! HY3131 R20..R35 configuration rows, [range][byte].', '',
       'use crate::hy3131::CFG_LEN;', '']
for m in re.finditer(r'/\* flash (0x[0-9a-f]+) \*/\s*static const uint8_t hy3131_cfg_(\w+)\[(\d+)\]\[HY3131_CFG_LEN\] = \{(.*?)\};', src, re.S):
    addr, name, n, body = m.groups()
    rows = re.findall(r'\{([^{}]*)\}', body)
    assert len(rows) == int(n), name
    out.append('/// flash %s' % addr)
    out.append('pub const CFG_%s: [[u8; CFG_LEN]; %s] = [' % (name.upper(), n))
    for r in rows:
        vals = [v.strip() for v in r.split(',') if v.strip()]
        assert len(vals) == 22, (name, len(vals))
        out.append('    [%s],' % ', '.join(vals))
    out.append('];')
    out.append('')
open(os.path.join(ROOT, 'src', 'hy3131_tables.rs'), 'w').write('\n'.join(out))
print('\n'.join(l for l in out if l.startswith('pub const')))
